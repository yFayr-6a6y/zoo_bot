package com.example.zoo_bot.service;

import com.example.zoo_bot.model.entity.ShelterType;
import org.springframework.stereotype.Service;

import java.util.HashMap;
import java.util.Map;

/**
 * Сервис для Этапа 2 — Консультация с потенциальным хозяином (как взять животное).
 * Содержит рекомендации по документам, обустройству дома, транспортировке и т.д.
 */
@Service
public class AdoptionService {

    /**
     * Список необходимых документов для усыновления
     */
    public String getRequiredDocuments(ShelterType shelterType) {
        return """
                📄 Необходимые документы для усыновления:
                
                • Паспорт гражданина РФ (оригинал)
                • Заполненная анкета потенциального усыновителя
                • Договор ответственного содержания (подписывается на месте)
                • Согласие всех членов семьи (если проживают совместно)
                """;
    }

    /**
     * Рекомендации по обустройству дома
     */
    public Map<String, String> getHomeSetupRecommendations(ShelterType shelterType, String animalType) {
        Map<String, String> recommendations = new HashMap<>();

        switch (animalType.toLowerCase()) {
            case "puppy", "щенок", "котенок" -> recommendations.put("Для щенка / котёнка", """
                    🏠 Рекомендации для щенка/котёнка:
                    
                    • Безопасность: спрятать провода, химию, мелкие предметы
                    • Место для сна и отдыха
                    • Лоток/пеленки + наполнитель
                    • Игрушки, когтеточка (для кошек)
                    • Постепенное знакомство с новым пространством
                    """);

            case "adult", "взрослый" -> recommendations.put("Для взрослого животного", """
                    🏠 Рекомендации для взрослого животного:
                    
                    • Своё постоянное место для сна
                    • Сохранение привычного рациона первое время
                    • Постепенное расширение пространства
                    • Соблюдение режима выгула/кормления
                    • Наблюдение за стрессом и адаптацией
                    """);

            case "special", "особенный", "ограниченные" -> recommendations.put("Для животного с ограниченными возможностями", """
                    ♿ Рекомендации для животного с ОВЗ:
                    
                    • Пандусы или ступеньки при необходимости
                    • Отсутствие высоких препятствий
                    • Специальные лежаки и миски на удобной высоте
                    • Дополнительное освещение (при проблемах со зрением)
                    • Более мягкий и терпеливый подход к адаптации
                    """);
        }

        return recommendations;
    }

    /**
     * Причины возможного отказа в усыновлении
     */
    public String getRefusalReasons(ShelterType shelterType) {
        return """
                🚫 Основные причины возможного отказа:
                
                • Несоответствие условий содержания требованиям приюта
                • Отсутствие опыта содержания собак данной породы/размера
                • Нежелание стерилизовать/кастрировать животное
                • Нестабильное финансовое положение
                • Аллергия у кого-то из членов семьи
                • Конфликт с другими животными в доме
                • Отсутствие возможности регулярных выгулов
                """;
    }

    /**
     * Советы кинолога по первичному общению с собакой
     */
    public String getKinologAdvice() {
        return """
                🐕 Советы кинолога по первичному общению:
                
                • Не перегружайте собаку в первые дни — дайте время на адаптацию
                • Соблюдайте чёткий режим кормления и выгула
                • Используйте только положительное подкрепление
                • Наблюдайте за языком тела собаки
                • Будьте последовательны в правилах
                • Не оставляйте собаку одну надолго в первые недели
                """;
    }

    /**
     * Рекомендации по проверенным кинологам
     */
    public String getRecommendedKinologs() {
        return """
                👨‍🏫 Рекомендуемые кинологи:
                
                • Кинологический центр "Верный друг" — +7 (495) 777-88-99
                • Специалист по поведению собак Анна Смирнова — @dog_psy
                • Школа "Пёс и человек" — +7 (916) 123-45-67
                
                Рекомендуется начинать занятия через 2–3 недели после адаптации.
                """;
    }

    /**
     * Рекомендации по транспортировке животного
     */
    public String getTransportRecommendations() {
        return """
                🚗 Рекомендации по транспортировке:
                
                • Используйте специальную переноску или клетку
                • Для крупных собак — намордник и надёжный поводок
                • Не кормите животное за 2–3 часа до поездки
                • Возьмите с собой ветеринарный паспорт и воду
                • По возможности возьмите любимую игрушку или подстилку
                """;
    }
}